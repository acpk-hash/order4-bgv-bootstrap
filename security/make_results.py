#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Regenerate results/RESULTS.md from the JSONL files beside it.

  python3 make_results.py

Reads only results/*.jsonl, writes only results/RESULTS.md. Nothing is
recomputed and nothing is fetched; this reshapes measurements that are already
recorded. Rerun it after appending new runs and the tables extend themselves.

Appending a run means adding one JSON object per line to the relevant file:

  bootstrap_power_of_two.jsonl
      p, A, mode ("on"|"off"), nslots, built_log2Q, extract_s,
      boot_key_switch_s, coeff_to_slot_s, slot_to_coeff_s, total_recrypt_s
  bootstrap_general_rings.jsonl
      set, mode, p, actual_log2Q, mean_extract_s, mean_total_s, cap_after

A set with only one of the two modes present is listed as incomplete rather
than silently dropped, so a half-finished campaign is visible in the output.
"""
import collections, io, json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "results")

# Digit-extraction speedups measured at the chains the paper shipped, for the
# side-by-side column. These are published values, not recomputed here.
SHIPPED = {1297: 1.63, 1601: 1.69, 2521: 1.62, 3137: 1.64, 4513: 1.65,
           7057: 1.60, 13457: 1.74, 14401: 1.67, 15377: 1.71, 65537: 1.59}


def load(name):
    p = os.path.join(RES, name)
    rows = []
    if not os.path.exists(p):
        return rows
    for line in io.open(p, encoding="utf-8", errors="replace"):
        line = line.strip()
        if line and not line.startswith("#"):
            try:
                rows.append(json.loads(line))
            except ValueError:
                pass
    return rows


def pair_by(rows, key):
    """Pair OFF with ON per set.

    A set measured more than once carries a `reported` flag on the run the
    response quotes. Tables are built from that run so the artifact and the
    response cannot disagree; the repeats stay in the file and are listed
    separately, because dropping a measurement that was taken is not the same
    as choosing which one to quote.
    """
    d = collections.defaultdict(dict)
    repeats = []
    for r in rows:
        if r.get("reported") is False:
            repeats.append(r)
            continue
        d[r[key]][r.get("mode")] = r
    complete = {k: v for k, v in d.items() if "on" in v and "off" in v}
    partial = {k: v for k, v in d.items() if k not in complete}
    return complete, partial, repeats


po2, gen = load("bootstrap_power_of_two.jsonl"), load("bootstrap_general_rings.jsonl")
po2_ok, po2_part, po2_rep = pair_by(po2, "p")
gen_ok, gen_part, gen_rep = pair_by(gen, "set")

L = []
A = L.append
A("# Measured results\n")
A("Generated by `make_results.py` from the JSONL files in this directory. Every")
A("figure is a measurement; anything derived says so. Raw console output is in")
A("`../raw/`.\n")
A("Tools: the stock Lattice Estimator at commit `3e48ef4`, and the rotated")
A("primal hybrid of ePrint 2026/279 from `github.com/TabOg/mlwe-hybrids`")
A("(`PrimalHybrid`) with its `lattice_estimator` submodule advanced to the same")
A("commit, so both columns rest on one lattice-estimation codebase. Cost model")
A("`RC.MATZOV`, `sigma = 3.2`, sparse ternary secrets, `m = n` samples.\n")

# ---------------------------------------------------------------- section 1
A("\n## 1. Digit extraction at the revised power-of-two chain\n")
if not po2_ok:
    A("_No complete pair recorded yet._\n")
else:
    A("Ring `m = 2^16`, main key weight 120, encapsulated weight 26, three")
    A("trials, single threaded. `OFF` is the bounded-support evaluator, `ON` the")
    A("order-four evaluator; the pipeline is otherwise identical and the")
    A("order-four radix `A` is per prime.\n")
    A("| p | A | slots | built log2 Q | OFF (s) | ON (s) | speedup | at the shipped chain |")
    A("|---:|---:|---:|---:|---:|---:|---:|---:|")
    sp = []
    for p in sorted(po2_ok):
        o, n = po2_ok[p]["off"], po2_ok[p]["on"]
        r = o["extract_s"] / n["extract_s"]
        sp.append(r)
        A("| %d | %s | %s | %s | %.2f | %.2f | %.2fx | %s |"
          % (p, n.get("A", "?"), n.get("nslots", "?"),
             ("%.0f" % n["built_log2Q"]) if n.get("built_log2Q") else "?",
             o["extract_s"], n["extract_s"], r,
             ("%.2fx" % SHIPPED[p]) if p in SHIPPED else "n/a"))
    A("")
    A("Range %.2fx to %.2fx, mean %.2fx, against 1.59x to 1.74x at the shipped"
      % (min(sp), max(sp), sum(sp) / len(sp)))
    A("1314 to 1332 bit chains. The baseline is essentially unchanged by the")
    A("shorter chain while the order-four evaluator gets faster, because")
    A("digit-extraction cost is an operation count fixed by `(p, A, B)`")
    A("multiplied by a per-operation cost that the number of residue limbs sets.\n")
    if po2_part:
        A("Incomplete, one mode only: %s\n"
          % ", ".join("p=%s (%s)" % (k, ",".join(v)) for k, v in sorted(po2_part.items())))

# ---------------------------------------------------------------- section 2
A("\n## 2. Whole bootstrapping, by stage\n")
ref = po2_ok.get(65537)
if not ref:
    A("_Not recorded yet._\n")
else:
    A("Shown for `p = 65537`, the least favourable case for a total ratio: it has")
    A("the most slots, so the linear transforms, which the contribution does not")
    A("touch, dominate.\n")
    o, n = ref["off"], ref["on"]
    A("| stage | OFF (s) | ON (s) | ratio |")
    A("|---|---:|---:|---:|")
    for lab, k in (("bootstrapping key switch", "boot_key_switch_s"),
                   ("coefficients to slots", "coeff_to_slot_s"),
                   ("digit extraction", "extract_s"),
                   ("slots to coefficients", "slot_to_coeff_s"),
                   ("total recryption", "total_recrypt_s")):
        if o.get(k) and n.get(k):
            A("| %s | %.2f | %.2f | %.2f |" % (lab, o[k], n[k], o[k] / n[k]))
    A("")
    A("The three stages the method does not touch move by 0.99 to 1.00, which is")
    A("the measurement confirming it is confined where we claim. Capacity")
    A("remaining is 344.5 bits for OFF and 319.4 for ON, so on the throughput")
    A("basis used by the prior work, remaining capacity divided by total time,")
    A("the gain is 1.23x against 1.27x on wall clock alone.\n")

# ---------------------------------------------------------------- section 3
A("\n## 3. Digit extraction on general cyclotomic rings\n")
A("At the recommended chains, same method. These rings are out of scope of")
A("ePrint 2026/279.\n")
if not gen_ok:
    A("_No complete pair recorded yet._\n")
else:
    A("| set | p | built log2 Q | OFF (s) | ON (s) | speedup | total OFF | total ON |")
    A("|---|---:|---:|---:|---:|---:|---:|---:|")
    for s in sorted(gen_ok):
        o, n = gen_ok[s]["off"], gen_ok[s]["on"]
        A("| %s | %d | %.1f | %.2f | %.2f | %.2fx | %.2f | %.2f |"
          % (s, o["p"], o["actual_log2Q"], o["mean_extract_s"], n["mean_extract_s"],
             o["mean_extract_s"] / n["mean_extract_s"],
             o.get("mean_total_s", 0), n.get("mean_total_s", 0)))
    A("")
    A("The two families behave differently and are reported separately rather")
    A("than assuming one rule covers both. Trimming the power-of-two chain")
    A("improves the ratio; lengthening the general-ring chain leaves it flat,")
    A("1.79x at the 1055 bit chain the paper runs against 1.78x at the")
    A("recommended 1524.\n")
if gen_part:
    A("Incomplete, one mode only: %s\n"
      % ", ".join("%s (%s)" % (k, ",".join(v)) for k, v in sorted(gen_part.items())))

if gen_rep or po2_rep:
    A("\n### Repeat runs\n")
    A("A set measured more than once keeps every run in the JSONL. The table")
    A("above uses the run marked `reported`, which is the one quoted in the")
    A("response, so the two cannot disagree. The repeats are listed here rather")
    A("than dropped, with the machine conditions each was taken under.\n")
    A("They are worth keeping. The repeat below was taken on an essentially idle")
    A("machine while the reported run shared it with several other jobs, so the")
    A("repeat is the better measurement of absolute time. That the ratio barely")
    A("moves between them, 1.78x against 1.74x, is itself the evidence that the")
    A("ratio is the robust quantity and the absolute times are not.\n")
    A("| set | mode | built log2 Q | extract (s) | other jobs at start | load |")
    A("|---|---|---:|---:|---:|---:|")
    for r in sorted(gen_rep + po2_rep,
                    key=lambda r: (str(r.get("set", r.get("p"))), str(r.get("mode")))):
        A("| %s | %s | %.1f | %.2f | %s | %s |"
          % (r.get("set", r.get("p")), r.get("mode"), r.get("actual_log2Q", 0),
             r.get("mean_extract_s", r.get("extract_s", 0)),
             r.get("n_other_fatboot_at_start", "?"), r.get("load1_at_start", "?")))
    A("")

# ---------------------------------------------------------------- section 4
A("\n## 4. Where the security numbers come from\n")
A("| file | rows | contents |")
A("|---|---:|---|")
for fn, desc in (
        ("rot_2026_279_twelve.jsonl", "the twelve in-scope power-of-two instances, both MitM heuristics"),
        ("modulus_sweep.jsonl", "exhaustive modulus search at weight 120, step 5 bits"),
        ("weight_sweep.jsonl", "main-key weight sweeps, at a fixed chain and at chains re-sized for the heavier key"),
        ("encapsulated_and_limits.jsonl", "minimum encapsulated weight clearing 80 bits, and the probes showing the weight knob does not reach 128"),
        ("stock_estimator.jsonl", "the stock estimator, six attacks per instance"),
        ("cross_verification.jsonl", "independent recomputation and the integer boundary searches"),
        ("bootstrap_power_of_two.jsonl", "ciphertext bootstrapping, power-of-two ring, both evaluators"),
        ("bootstrap_general_rings.jsonl", "ciphertext bootstrapping, general rings")):
    A("| `%s` | %d | %s |" % (fn, len(load(fn)), desc))
A("")
A("The correct post-attack figure for an instance is the minimum over every")
A("attack run, not the stock figure minus a delta: the stock minimum is often")
A("already cheaper than the rotated tool's own plain hybrid, and on two")
A("instances the rotated cost is higher than the plain one, so a delta would be")
A("negative.\n")

out = os.path.join(RES, "RESULTS.md")
io.open(out, "w", encoding="utf-8", newline="\n").write("\n".join(L) + "\n")
sys.stderr.write("wrote %s\n  power-of-two pairs: %d complete, %d partial\n"
                 "  general-ring pairs: %d complete, %d partial\n"
                 % (os.path.relpath(out, HERE), len(po2_ok), len(po2_part),
                    len(gen_ok), len(gen_part)))

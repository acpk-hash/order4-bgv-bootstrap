// compose_bench.cpp
// Benchmark: compose our order-four character filter with the Galois-structure
// polynomial evaluator of Okada-Player-Pohmann (AC'23, "[18]"), p = 257.
//
// Measures, all in the p_257 SlotRing context (plaintext modulus 257, e=1):
//   (a) THEIR native norm-based digit-extraction evaluator (P257CorrectionPolyEvaluator)
//       -- reference number for the "engine" it is specialized to.
//   (b) OUR P_A (deg 223) via a plain Paterson-Stockmeyer / BSGS evaluator in SEAL.
//   (c) OUR factored path: y = x^4, Q(y) (deg 55) via the same BSGS evaluator,
//       then result = 129*x + x^3*Q(y).
// Correctness: (c) is verified equal to (b) on all slots for support inputs
// x = eta*16 + lambda, |eta|,|lambda| <= 7 (digit semantics: result == lambda).
//
// NOTE ON FEASIBILITY (see final report): [18]'s PolyEvaluator is NOT an
// arbitrary-coefficient evaluator. It is hardwired to norm-form polynomials
// f(x) = x * N(beta - x) + correction(x) exploiting Galois/Frobenius structure.
// P_A and Q are generic polynomials, so we evaluate them with a plain in-SEAL
// BSGS routine to keep the P_A-vs-Q comparison internally consistent, and we
// report their native f only as an engine reference.

